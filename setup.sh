# ----------------------------------------------------------------------------
#  Interactive menu
# ----------------------------------------------------------------------------
show_menu() {
    clear
    echo -e "${BOLD}${CYAN}"
    echo "╔══════════════════════════════════════════════════════════════╗"
    echo "║       Aurora Telegram Downloader Bot - Manager            ║"
    echo "║       SoundCloud | Spotify | YouTube | Pinterest |          ║"
    echo "║       Instagram | TikTok | Twitter (X)                       ║"
    echo "╚══════════════════════════════════════════════════════════════╝"
    echo -e "${NC}"
    echo -e "  Project:  ${PROJECT_DIR}"
    if [[ -f "$CONFIG_FILE" ]]; then
        local svc_kind="system"
        [[ "$USER_SERVICE" == "true" ]] && svc_kind="user"
        echo -e "  Service:  ${GREEN}${SERVICE_NAME}${NC} (${svc_kind})"
    else
        echo -e "  Service:  ${YELLOW}not configured${NC}"
    fi
    if [[ -f "$DB_PATH" ]]; then
        echo -e "  Database: ${GREEN}$(du -h "$DB_PATH" | cut -f1)${NC}"
    fi
    echo ""
    echo -e "  ${GREEN}1)${NC}  Install / Setup ${YELLOW}(first time)${NC}"
    echo -e "  ${GREEN}2)${NC}  Update Code & Dependencies"
    echo -e "  ${GREEN}3)${NC}  Restart Service"
    echo -e "  ${GREEN}4)${NC}  Stop Service"
    echo -e "  ${GREEN}5)${NC}  Service Status"
    echo -e "  ${GREEN}6)${NC}  View Logs ${YELLOW}(live)${NC}"
    echo -e "  ${GREEN}7)${NC}  Reconfigure ${YELLOW}(token / channel / port)${NC}"
    echo -e "  ${GREEN}8)${NC}  Backup Database & Config"
    echo -e "  ${GREEN}9)${NC}  Restore from Backup"
    echo -e "  ${GREEN}10)${NC} Health Check"
    echo -e "  ${GREEN}11)${NC} Remove Service"
    echo -e "  ${RED}12)${NC} ${RED}Full Uninstall${NC} ${YELLOW}(service + venv + logs + db)${NC}"
    echo -e "  ${GREEN}0)${NC}  Exit"
    echo ""
    read -rp "Choose an option [0-12]: " choice

    case "$choice" in
        1)  do_install ;;
        2)  do_update ;;
        3)  do_restart ;;
        4)  do_stop ;;
        5)  do_status ;;
        6)  do_logs ;;
        7)  do_reconfigure ;;
        8)  do_backup ;;
        9)  do_restore ;;
        10) do_health ;;
        11) do_remove_service ;;
        12) do_full_uninstall ;;
        0)  echo -e "${GREEN}Goodbye!${NC}"; exit 0 ;;
        *)  err "Invalid option"; sleep 1 ;;
    esac
}

